SANDBOX_MEM_MB=256
SANDBOX_CPUS=0.5
SANDBOX_TIMEOUT=10
AUTO_PUBLISH=0

# Scale
GEN_STAGES=10
GEN_LESSONS_PER_STAGE=20
GEN_OUTLINE_ENABLED=1
GEN_LAZY_ON_OPEN=1
GEN_WARM_LESSONS=0
GEN_PREBUILD_ON_OPEN=1
GEN_PREBUILD_MAX=0
GEN_PREBUILD_PRIORITY=2
AI_RESERVE_PCT=25
AI_RESERVE_RPD=80
GEN_WORKER_CONCURRENCY=2
GEN_QUEUE_POLL=5
