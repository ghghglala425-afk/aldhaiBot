#!/usr/bin/env bash
set -euo pipefail

# =============================================================================
# Oracle Cloud ARM Setup Script for Cyber Academy Bot
# Run this ONCE on the Oracle Cloud VM after initial setup
# =============================================================================

# ===== CONFIGURATION - EDIT THESE VALUES =====
DUCKDNS_DOMAIN="yourbot"           # Your duckdns subdomain (without .duckdns.org)
DUCKDNS_TOKEN="YOUR_DUCKDNS_TOKEN" # Get from duckdns.org after login
EMAIL="your@email.com"             # For Let's Encrypt notifications
WEBHOOK_SECRET="$(openssl rand -hex 32)"  # Auto-generate secure secret
DB_PASSWORD="$(openssl rand -hex 24)"      # Auto-generate secure DB password
# =============================================================================

PROJECT_DIR="$HOME/bot-project"
DOMAIN="${DUCKDNS_DOMAIN}.duckdns.org"

echo "=========================================="
echo "Oracle Cloud ARM Setup - Cyber Academy Bot"
echo "=========================================="
echo "Domain: $DOMAIN"
echo "Project dir: $PROJECT_DIR"
echo ""

# -----------------------------------------------------------------------------
# System updates
# -----------------------------------------------------------------------------
echo "[1/8] Updating system packages..."
sudo apt-get update && sudo apt-get upgrade -y

# -----------------------------------------------------------------------------
# Install Docker & Docker Compose
# -----------------------------------------------------------------------------
echo "[2/8] Installing Docker..."
if ! command -v docker &> /dev/null; then
    curl -fsSL https://get.docker.com | sh
    sudo usermod -aG docker $USER
    echo "Docker installed. You may need to log out and back in for group changes."
else
    echo "Docker already installed."
fi

# Docker Compose v2 (plugin)
if ! docker compose version &> /dev/null; then
    echo "Installing Docker Compose plugin..."
    sudo apt-get install -y docker-compose-plugin
fi

# -----------------------------------------------------------------------------
# Configure firewall
# -----------------------------------------------------------------------------
echo "[3/8] Configuring firewall (ufw)..."
sudo ufw allow 22/tcp    # SSH
sudo ufw allow 80/tcp    # HTTP (ACME challenge)
sudo ufw allow 443/tcp   # HTTPS
sudo ufw allow 8443/tcp  # Webhook reserve port
sudo ufw --force enable

# -----------------------------------------------------------------------------
# Setup DuckDNS auto-update
# -----------------------------------------------------------------------------
echo "[4/8] Setting up DuckDNS auto-update..."
cat > /tmp/duckdns-update.sh <<EOF
#!/bin/bash
curl -s "https://www.duckdns.org/update?domains=${DUCKDNS_DOMAIN}&token=${DUCKDNS_TOKEN}&ip=" >/dev/null
EOF
chmod +x /tmp/duckdns-update.sh
sudo mv /tmp/duckdns-update.sh /usr/local/bin/duckdns-update

# Add to crontab (every 5 minutes)
(crontab -l 2>/dev/null | grep -v duckdns-update; echo "*/5 * * * * /usr/local/bin/duckdns-update") | crontab -
echo "DuckDNS update scheduled every 5 minutes."

# Run once now
/usr/local/bin/duckdns-update
echo "Initial DuckDNS update sent."

# -----------------------------------------------------------------------------
# Create project directory structure
# -----------------------------------------------------------------------------
echo "[5/8] Creating project directories..."
mkdir -p "$PROJECT_DIR"/{certbot/conf,certbot/www,nginx,scripts}
cd "$PROJECT_DIR"

# -----------------------------------------------------------------------------
# Create .env.prod from template
# -----------------------------------------------------------------------------
echo "[6/8] Creating .env.prod..."
cat > "$PROJECT_DIR/.env.prod" <<EOF
# =============================================================================
# Cyber Academy Bot - Production Environment
# Generated by setup_oracle.sh on $(date)
# =============================================================================

# ===== Telegram =====
BOT_TOKEN=YOUR_BOT_TOKEN_HERE
BOT_MODE=webhook
WEBHOOK_URL=https://${DOMAIN}
WEBHOOK_PATH=/webhook
WEBHOOK_PORT=8443
WEBHOOK_SECRET=${WEBHOOK_SECRET}

ADMIN_IDS=5444436820

# ===== AI (Free Tier) =====
AI_FREE_MODE=1
AI_PROVIDER_ORDER=gemini,groq,openrouter
AI_DAILY_TOKEN_BUDGET=2000000
GEMINI_API_KEY=YOUR_GEMINI_API_KEY_HERE
GEMINI_API_KEY_2=
GEMINI_MODEL=gemini-3.5-flash-lite
GEMINI_FALLBACK_MODEL=gemini-3.8-flash
GEMINI_MODEL_CHAIN=gemini-3.5-flash-lite,gemini-3.8-flash,gemini-3.6-flash,gemini-3.1-flash-lite
GEMINI_AUTODETECT=1
GEMINI_RPM=10
GEMINI_RPD=1000
GEMINI_TPD=2000000
GROQ_API_KEY=
GROQ_MODEL=openai/gpt-oss-120b
GROQ_RPM=30
GROQ_RPD=1000
GROQ_TPD=200000
OPENROUTER_API_KEY=
OPENROUTER_MODEL=meta-llama/llama-3.3-70b-instruct:free
OPENROUTER_RPM=20
OPENROUTER_RPD=50
OPENROUTER_TPD=0
AI_API_KEY=
AI_BASE_URL=https://api.openai.com/v1
AI_MODEL=gpt-4o-mini
AI_TIMEOUT=120
AI_MAX_TOKENS=8192
AI_JSON_MODE=auto
AI_MAX_RETRIES=3

# ===== Database / Cache =====
DATABASE_URL=postgresql+asyncpg://cyber:${DB_PASSWORD}@db:5432/cyberbot
REDIS_URL=redis://redis:6379/0

# ===== Security =====
SECRET_KEY=$(openssl rand -hex 32)
ACCESS_TOKEN_TTL_MIN=10080
JWT_ALGORITHM=HS256

# ===== App =====
ENV=prod
LOG_LEVEL=INFO
MINIAPP_URL=
API_BASE_URL=
# ===== Content Generation =====
VERIFY_EXEC=0
# خدمة تنفيذ خارجية معزولة — فارغة = معطّل بلا Docker
# مثال: EXEC_PROVIDER=judge0 و EXEC_API_URL=https://ce.judge0.com
EXEC_PROVIDER=
EXEC_API_URL=
EXEC_API_KEY=
EXEC_API_TIMEOUT=20
GEN_MIN_CODES=6
GEN_FAST_CODES=4
GEN_FAST_MIN_CHARS=2800
GEN_MIN_CHARS=4000
GEN_MIN_QUESTIONS=8
GEN_MIN_USAGES=8
GEN_ENRICH_ATLAS=1
GEN_ATLAS_BATCH=5
