GEN_LESSON_TIMEOUT=1800
GEN_QUEUE_MAX=400
# Targets
TARGET_EXTERNAL_URLS=
PROXY_ALLOWED_HOSTS=localhost,127.0.0.1
PROXY_TIMEOUT=20
EOF

echo ".env.prod created. IMPORTANT: Edit it and add your BOT_TOKEN and GEMINI_API_KEY!"

# -----------------------------------------------------------------------------
# Create directory structure for certbot
# -----------------------------------------------------------------------------
echo "[7/8] Creating certbot directories..."
mkdir -p certbot/conf certbot/www

# -----------------------------------------------------------------------------
# Final instructions
# -----------------------------------------------------------------------------
echo "[8/8] Setup complete!"
echo ""
echo "=========================================="
echo "NEXT STEPS (run these commands):"
echo "=========================================="
echo ""
echo "1. Edit .env.prod with your actual tokens:"
echo "   nano $PROJECT_DIR/.env.prod"
echo ""
echo "2. Copy docker-compose.prod.yml, nginx.conf, Dockerfile.prod to $PROJECT_DIR"
echo ""
echo "3. Build and start services:"
echo "   cd $PROJECT_DIR"
echo "   docker compose -f docker-compose.prod.yml up -d --build"
echo ""
echo "4. Get SSL certificate (after DNS propagates):"
echo "   docker compose -f docker-compose.prod.yml run --rm certbot \\"
echo "     certonly --webroot -w /var/www/certbot \\"
echo "     -d ${DOMAIN} \\"
echo "     --email YOUR_EMAIL --agree-tos --non-interactive"
echo ""
echo "4. Restart nginx to pick up certificates:"
echo "   docker compose -f docker-compose.prod.yml restart nginx"
echo ""
echo "5. Set Telegram webhook:"
echo "   curl -X POST \"https://api.telegram.org/bot\$BOT_TOKEN/setWebhook\" \\"
echo "     -H \"Content-Type: application/json\" \\"
echo "     -d '{\"url\": \"https://${DOMAIN}/webhook\", \"secret_token\": \"WEBHOOK_SECRET_FROM_ENV\"}'"
echo ""
echo "6. Verify webhook:"
echo "   curl \"https://api.telegram.org/bot\$BOT_TOKEN/getWebhookInfo\""
echo ""
echo "=========================================="
echo "IMPORTANT REMINDERS:"
echo "=========================================="
echo "1. Replace YOUR_BOT_TOKEN_HERE and YOUR_GEMINI_API_KEY_HERE in .env.prod"
echo "2. Ensure duckdns domain resolves: dig ${DOMAIN}"
echo "3. Open Oracle Cloud security list ports: 22, 80, 443, 8443"
echo "4. ARM architecture: all images use linux/arm64 platform"
echo "5. Monitor logs: docker compose -f docker-compose.prod.yml logs -f"
echo ""
echo "Log files location: docker compose logs -f"
echo "Project directory: $PROJECT_DIR"
echo ""
echo "Setup script completed successfully!"